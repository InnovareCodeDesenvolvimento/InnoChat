import { describe, expect, it } from "vitest";
import { maskBrPhone } from "./phone-mask";

describe("maskBrPhone", () => {
  it.each([
    ["", ""],
    ["8", "(8"],
    ["84", "(84"],
    ["849", "(84) 9"],
    ["84999", "(84) 999"],
    ["849999", "(84) 9999"],
    ["8499999", "(84) 9999-9"],
    ["8431132584", "(84) 3113-2584"],
    ["84999998888", "(84) 99999-8888"],
    ["(84) 99999-8888", "(84) 99999-8888"],
    ["+55 84 99999-8888", "(84) 99999-8888"],
    ["849999988889999", "(84) 99999-8888"],
  ])("%s -> %s", (input, expected) => {
    expect(maskBrPhone(input)).toBe(expected);
  });
});
